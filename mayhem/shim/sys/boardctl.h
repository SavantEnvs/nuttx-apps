/* mayhem/shim/sys/boardctl.h — host stand-in: there is no board to control,
 * so boardctl() always fails with ENOSYS (environment mock, not target code). */
#ifndef __MAYHEM_SHIM_SYS_BOARDCTL_H
#define __MAYHEM_SHIM_SYS_BOARDCTL_H
#include <errno.h>
#include <stdint.h>
enum
{
  BOARDIOC_INIT = 1, BOARDIOC_FINALINIT, BOARDIOC_POWEROFF, BOARDIOC_RESET,
  BOARDIOC_RESET_CAUSE, BOARDIOC_PM_CONTROL, BOARDIOC_UNIQUEID,
  BOARDIOC_MKRD, BOARDIOC_ROMDISK, BOARDIOC_APP_SYMTAB, BOARDIOC_OS_SYMTAB,
  BOARDIOC_BUILTINS, BOARDIOC_USBDEV_CONTROL, BOARDIOC_NX_START,
  BOARDIOC_VNC_START, BOARDIOC_NXTERM, BOARDIOC_NXTERM_IOCTL,
  BOARDIOC_TESTSET, BOARDIOC_BOOT_IMAGE, BOARDIOC_START_CPU,
  BOARDIOC_MACADDR, BOARDIOC_SWITCH_BOOT, BOARDIOC_RESET_RESET,
  BOARDIOC_SPINLOCK, BOARDIOC_USER
};
enum boardioc_resetcause_e
{
  BOARDIOC_RESETCAUSE_NONE = 0, BOARDIOC_RESETCAUSE_SYS_CHIPPOR,
  BOARDIOC_RESETCAUSE_SYS_RWDT, BOARDIOC_RESETCAUSE_SYS_BOR,
  BOARDIOC_RESETCAUSE_CORE_SOFT, BOARDIOC_RESETCAUSE_CORE_DPS,
  BOARDIOC_RESETCAUSE_CORE_MWDT, BOARDIOC_RESETCAUSE_CORE_RWDT,
  BOARDIOC_RESETCAUSE_CORE_RTC, BOARDIOC_RESETCAUSE_CPU_MWDT,
  BOARDIOC_RESETCAUSE_CPU_SOFT, BOARDIOC_RESETCAUSE_CPU_RWDT,
  BOARDIOC_RESETCAUSE_PIN, BOARDIOC_RESETCAUSE_LOWPOWER,
  BOARDIOC_RESETCAUSE_UNKOWN
};
#define BOARDIOC_SOFTRESETCAUSE_USER_REBOOT      0
#define BOARDIOC_SOFTRESETCAUSE_ENTER_BOOTLOADER 1
struct boardioc_boot_info_s
{
  const char *path;
  uintptr_t header_size;
};
static inline int boardctl(unsigned int cmd, uintptr_t arg)
{
  (void)cmd; (void)arg;
  errno = ENOSYS;
  return -1;
}
#endif
